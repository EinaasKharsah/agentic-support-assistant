"""Run the agent on the evaluation set and report how good its decisions are.

Usage:
  python evaluation/run_eval.py --scores-only          # fast, no LLM: see similarity scores per type
  python evaluation/run_eval.py --mode llm             # LLM decides + guardrails
  python evaluation/run_eval.py --mode rules           # score-only baseline
  python evaluation/run_eval.py --mode llm --split dev # only the dev half
  python evaluation/run_eval.py --set robustness       # typos, other languages, injection, ...
  python evaluation/run_eval.py --set hard --with-answers  # held-out hard cases (never used for tuning)
  python evaluation/run_eval.py --file questions.csv --with-answers  # your own questions (see load_csv)

Answers are not generated by default (only decisions), to keep runs fast.
Add --with-answers to also generate and save the final answer texts.
"""

import argparse
import csv
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.agent import SupportAgent  # noqa: E402
from app.config import settings  # noqa: E402
from app.embeddings import FastEmbedEmbedder  # noqa: E402
from app.knowledge_base import load_knowledge_base  # noqa: E402
from app.llm import OllamaClient  # noqa: E402
from app.vector_store import VectorStore, make_client  # noqa: E402
from evaluation.metrics import compute_metrics, format_report, row_error  # noqa: E402

EVAL_SETS = {
    "main": ROOT / "evaluation" / "eval_set.json",
    "robustness": ROOT / "evaluation" / "robustness_set.json",
    # Written after all tuning was finished and never used to change the agent.
    "hard": ROOT / "evaluation" / "hard_set.json",
    # Development examples for the fixes made after the held-out run (near-misses, other
    # languages, ...). New questions, not copied from the hard set.
    "fixes_dev": ROOT / "evaluation" / "fixes_dev_set.json",
}
RESULTS_DIR = ROOT / "evaluation" / "results"


def load_eval_set(name: str, split: str) -> list[dict]:
    items = json.loads(EVAL_SETS[name].read_text(encoding="utf-8"))
    return [item for item in items if split == "all" or item.get("split", "test") == split]


def load_csv(path: Path) -> list[dict]:
    """A question set written in a plain text editor, one question per line:

        question;expected;cards
        My refund hasn't arrived yet, what should I do?;answer;Q5
        I have a problem with billing;clarify;Q4 Q5 Q6
        What is the weather today?;decline;

    expected is answer, clarify or decline, or several joined by | (answer|clarify).
    cards are the right card ids, separated by spaces (empty for a decline).
    """
    items = []
    with path.open(encoding="utf-8-sig", newline="") as file:
        for row in csv.DictReader(file, delimiter=";"):
            question = (row.get("question") or "").strip()
            if not question:
                continue
            actions = [a.strip() for a in (row.get("expected") or "").split("|") if a.strip()]
            if not actions or any(a not in ("answer", "clarify", "decline") for a in actions):
                raise ValueError(f"Line with question {question!r}: expected must be answer, clarify or decline")
            items.append(
                {
                    "id": f"V{len(items) + 1:02d}",
                    "question": question,
                    "expected_action": actions[0] if len(actions) == 1 else actions,
                    "expected_cards": (row.get("cards") or "").split(),
                }
            )
    return items


def print_scores(store: VectorStore, items: list[dict]) -> None:
    """Show the top similarity score per question, grouped by expected action.
    Used to choose MIN_RELEVANCE on the dev split."""
    for action in ["answer", "clarify", "decline"]:
        print(f"\n{action.upper()}")
        for item in items:
            expected = item["expected_action"]
            if (expected[0] if isinstance(expected, list) else expected) != action:
                continue
            matches = store.search(item["question"], top_k=3)
            top = "  ".join(f"{m.entry.id}={m.score:.3f}" for m in matches)
            print(f"  {item['id']}  {top}   {item['question']}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", default=settings.agent_mode, choices=["llm", "rules"])
    parser.add_argument("--set", default="main", choices=list(EVAL_SETS))
    parser.add_argument("--file", type=Path, help="a question set in CSV format (overrides --set)")
    parser.add_argument("--split", default="all", choices=["all", "dev", "test"])
    parser.add_argument("--scores-only", action="store_true")
    parser.add_argument("--with-answers", action="store_true")
    args = parser.parse_args()

    items = load_csv(args.file) if args.file else load_eval_set(args.set, args.split)
    entries = load_knowledge_base(ROOT / settings.knowledge_base_path)
    store = VectorStore(make_client(None), FastEmbedEmbedder(settings.embedding_model), "eval_kb")
    store.index(entries)

    if args.scores_only:
        print_scores(store, items)
        return

    llm = OllamaClient(settings.ollama_url, settings.ollama_model, settings.llm_timeout_seconds)
    agent = SupportAgent(
        store, llm,
        min_relevance=settings.min_relevance,
        ambiguity_gap=settings.ambiguity_gap,
        second_check_gap=settings.second_check_gap,
        rewrite_weak_queries=settings.rewrite_weak_queries,
        mode=args.mode,
        generate_answers=args.with_answers,
    )

    rows = []
    for i, item in enumerate(items, 1):
        start = time.perf_counter()
        response = agent.respond(item["question"])
        seconds = time.perf_counter() - start
        row = {
            **item,
            "predicted_action": response.action.value,
            "predicted_card": response.source,
            "options": [o.card_id for o in response.options],
            "top3_cards": [m.entry.id for m in response.matches],
            "top_score": round(response.confidence, 3),
            "decided_by": response.decided_by,
            "search_query": response.search_query,
            "reason": response.reason,
            "message": response.message,
            "seconds": round(seconds, 2),
        }
        rows.append(row)
        ok = "OK " if row_error(row) is None else "XX "
        expected = "/".join(item["expected_action"]) if isinstance(item["expected_action"], list) else item["expected_action"]
        print(f"{ok}{i:>2}/{len(items)} {item['id']} expected={expected:<14} "
              f"got={row['predicted_action']:<7} {response.source or '':<4} {item['question']}")

    check = ""
    if args.mode == "llm":
        check = f"_check{settings.second_check_gap}" + ("_rewrite" if settings.rewrite_weak_queries else "")
    if args.file:
        prefix = f"{args.file.stem}_"
    else:
        prefix = "" if args.set == "main" else f"{args.set}_"
    name = f"{prefix}{args.mode}_{settings.ollama_model.replace(':', '-')}_{args.split}{check}"
    metrics = compute_metrics(rows)
    report = format_report(name, metrics)
    print("\n" + report)

    RESULTS_DIR.mkdir(exist_ok=True)
    out = RESULTS_DIR / f"{name}.json"
    out.write_text(json.dumps({"metrics": metrics, "rows": rows}, indent=2), encoding="utf-8")
    print(f"\nSaved: {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
