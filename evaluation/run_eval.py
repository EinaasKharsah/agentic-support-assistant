"""Run the agent on the evaluation set and report how good its decisions are.

Usage:
  python evaluation/run_eval.py --scores-only          # fast, no LLM: see similarity scores per type
  python evaluation/run_eval.py --mode llm             # LLM decides + guardrails
  python evaluation/run_eval.py --mode rules           # score-only baseline
  python evaluation/run_eval.py --mode llm --split dev # only the dev half

Answers are not generated by default (only decisions), to keep runs fast.
Add --with-answers to also generate and save the final answer texts.
"""

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.agent import SupportAgent  # noqa: E402
from app.config import settings  # noqa: E402
from app.embeddings import FastEmbedEmbedder  # noqa: E402
from app.knowledge_base import load_knowledge_base  # noqa: E402
from app.llm import OllamaClient  # noqa: E402
from app.vector_store import VectorStore, make_client  # noqa: E402
from evaluation.metrics import compute_metrics, format_report  # noqa: E402

EVAL_SET = ROOT / "evaluation" / "eval_set.json"
RESULTS_DIR = ROOT / "evaluation" / "results"


def load_eval_set(split: str) -> list[dict]:
    items = json.loads(EVAL_SET.read_text(encoding="utf-8"))
    return [item for item in items if split == "all" or item["split"] == split]


def print_scores(store: VectorStore, items: list[dict]) -> None:
    """Show the top similarity score per question, grouped by expected action.
    Used to choose MIN_RELEVANCE on the dev split."""
    for action in ["answer", "clarify", "decline"]:
        print(f"\n{action.upper()}")
        for item in items:
            if item["expected_action"] != action:
                continue
            matches = store.search(item["question"], top_k=3)
            top = "  ".join(f"{m.entry.id}={m.score:.3f}" for m in matches)
            print(f"  {item['id']}  {top}   {item['question']}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", default=settings.agent_mode, choices=["llm", "rules"])
    parser.add_argument("--split", default="all", choices=["all", "dev", "test"])
    parser.add_argument("--scores-only", action="store_true")
    parser.add_argument("--with-answers", action="store_true")
    args = parser.parse_args()

    items = load_eval_set(args.split)
    entries = load_knowledge_base(ROOT / settings.knowledge_base_path)
    store = VectorStore(make_client(None), FastEmbedEmbedder(settings.embedding_model), "eval_kb")
    store.index(entries)

    if args.scores_only:
        print_scores(store, items)
        return

    llm = OllamaClient(settings.ollama_url, settings.ollama_model, settings.llm_timeout_seconds)
    agent = SupportAgent(
        store, llm,
        min_relevance=settings.min_relevance,
        ambiguity_gap=settings.ambiguity_gap,
        mode=args.mode,
        generate_answers=args.with_answers,
    )

    rows = []
    for i, item in enumerate(items, 1):
        start = time.perf_counter()
        response = agent.respond(item["question"])
        seconds = time.perf_counter() - start
        row = {
            **item,
            "predicted_action": response.action.value,
            "predicted_card": response.source,
            "options": [o.card_id for o in response.options],
            "top3_cards": [m.entry.id for m in response.matches],
            "top_score": round(response.confidence, 3),
            "decided_by": response.decided_by,
            "reason": response.reason,
            "message": response.message,
            "seconds": round(seconds, 2),
        }
        rows.append(row)
        ok = "OK " if row["predicted_action"] == item["expected_action"] else "XX "
        print(f"{ok}{i:>2}/{len(items)} {item['id']} expected={item['expected_action']:<7} "
              f"got={row['predicted_action']:<7} {response.source or '':<4} {item['question']}")

    name = f"{args.mode}_{settings.ollama_model.replace(':', '-')}_{args.split}"
    metrics = compute_metrics(rows)
    report = format_report(name, metrics)
    print("\n" + report)

    RESULTS_DIR.mkdir(exist_ok=True)
    out = RESULTS_DIR / f"{name}.json"
    out.write_text(json.dumps({"metrics": metrics, "rows": rows}, indent=2), encoding="utf-8")
    print(f"\nSaved: {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
